#!/usr/bin/env node
/**
 * Сверка паспортов со следами приёмки: не отказала ли приёмка молча.
 *
 * Сломанный хук приёмки не останавливает работу — и не оставляет следа.
 * Ответ проходит так, будто правила не было. Паспорт пишется до работы и
 * знает, какое правило объявлено; значит «правило объявлено, а следа приёмки
 * нет» — обнаружимо машинно.
 *
 * Оба следа лежат в одном каталоге: паспорт `agent-<id>.pasport.json` и
 * след приёмки `agent-<id>.priyomka.jsonl` рядом. Это не удобство, а условие
 * работоспособности: первая редакция брала паспорта из общего хранилища, а
 * журнал приёмки — из каталога рядом с собой, и давала сто процентов ложных
 * тревог, потому что сверяла следы, записанные в разных системах координат.
 *
 * Обязанность считается по полю `правилоПриёмки` в паспорте — его объявляет
 * сама позиция. Прежняя редакция считала по хукам из настроек и записывала в
 * нарушители позицию без правила, которая справедливо прошла без вмешательства.
 *
 * Запуск: node .qwen/hooks/svodka.mjs [каталог проекта в ~/.qwen/projects]
 */
import { readFileSync, readdirSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { homedir } from 'node:os';

const корень = join(homedir(), '.qwen', 'projects');
const цель = process.argv[2];
const проекты = цель ? [цель] : (existsSync(корень) ? readdirSync(корень) : []);

/** След приёмки рядом с паспортом: сколько оборотов и чем кончилось. */
function прочитатьСлед(каталог, агент) {
  const путь = join(каталог, `agent-${агент}.priyomka.jsonl`);
  if (!existsSync(путь)) return null;
  const записи = readFileSync(путь, 'utf8').split('\n').filter((с) => с.trim())
    .map((с) => { try { return JSON.parse(с); } catch { return null; } })
    .filter(Boolean);
  if (!записи.length) return null;
  const итог = записи[записи.length - 1].итог;
  // НЕ-СВЕРЕНО значит, что приёмка отработала, но сверить было не с чем:
  // журнал недоступен или пуст. Считать это благополучием нельзя — позиция
  // числится обязанной, а обязанность не проверена.
  return { оборотов: записи.length, итог, сверено: итог !== 'НЕ-СВЕРЕНО' };
}

const немые = [], принятые = [], несверяемые = [];
let безПравила = 0;

for (const проект of проекты) {
  const каталогПроекта = join(корень, проект, 'subagents');
  if (!existsSync(каталогПроекта)) continue;
  for (const сессия of readdirSync(каталогПроекта)) {
    const каталог = join(каталогПроекта, сессия);
    for (const файл of readdirSync(каталог).filter((ф) => ф.endsWith('.pasport.json'))) {
      let п;
      try { п = JSON.parse(readFileSync(join(каталог, файл), 'utf8')); } catch { continue; }

      const правило = п.рамка?.правилоПриёмки;

      // Поля нет вовсе — паспорт прежней редакции. Сверять нечем, и молчать об
      // этом нельзя: молчание тут неотличимо от благополучия.
      if (правило === undefined) { несверяемые.push(п); continue; }

      // Позиция правила не объявляла — приёмке нечего было делать.
      if (правило === null) { безПравила++; continue; }

      const след = прочитатьСлед(каталог, п.агент);
      (след?.сверено ? принятые : немые).push({ п, правило, след });
    }
  }
}

for (const { п, правило, след } of принятые) {
  console.log(`✓ ${п.позиция.padEnd(12)} ${п.агент.slice(0, 26).padEnd(28)} ${правило.padEnd(18)} ` +
    `${след.итог.toLowerCase()}, оборотов: ${след.оборотов}`);
}
for (const { п, правило, след } of немые) {
  const что = след ? 'сверить было не с чем' : 'приёмка не отработала';
  console.log(`✗ ${п.позиция.padEnd(12)} ${п.агент.slice(0, 26).padEnd(28)} ${правило.padEnd(18)} ${что.padEnd(22)} ${п.время}`);
}
for (const п of несверяемые) {
  console.log(`? ${п.позиция.padEnd(12)} ${п.агент.slice(0, 26).padEnd(28)} паспорт прежней редакции, сверять нечем  ${п.время}`);
}

console.log(`\nобязаны приёмкой: ${принятые.length + немые.length}, ` +
  `без следа приёмки: ${немые.length}, ` +
  `без объявленного правила: ${безПравила}, ` +
  `не сверяемо: ${несверяемые.length}`);
process.exit(немые.length ? 1 : 0);
