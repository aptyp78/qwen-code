#!/usr/bin/env node
/**
 * Приёмка продукта субагента.
 *
 * Машина считает успехом сам факт молчания модели: если цикл не оборвался по
 * лимиту, ставится GOAL. Этот хук заменяет молчание сдачей работы.
 *
 * Первая редакция проверяла форму — наличие строки в ответе — и была отброшена
 * после первого же прогона: агент написал «НЕРАЗЛИЧЕНО: ничего не осталось
 * невыясненным», формально выполнил и содержательно не сделал ничего. Проверка
 * формы узаконивает пустышку и потому хуже отсутствия проверки.
 *
 * Расширение .mjs, а не .js: хук запускается в каталоге пользователя, где
 * может не быть package.json с type=module, и тогда import падает.
 *
 * Здесь проверка сверяется С МАТЕРИАЛОМ, а не с шаблоном. Устройство взято у
 * рубрики библиотеки: сначала машина считает то, что является фактом, и её
 * вердикт не может быть переписан суждением.
 */

import { readFileSync, appendFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ЖУРНАЛ = join(dirname(fileURLToPath(import.meta.url)), 'priyomka.log');

/** Пустые заявления: форма соблюдена, содержания нет. */
const ПУСТЫШКИ = [
  /ничего не оста/i, /всё выяснен/i, /все выяснен/i, /нет невыясн/i,
  /данных достаточно/i, /вопросов нет/i, /полностью прочитан/i, /^\s*(нет|—|-)\s*$/i,
];

/** Слова, по которым нельзя судить о присутствии факта в материале. */
const ШУМ = new Set(['этот','эта','было','быть','есть','весь','вся','все','для','как','что','или','при','над','под','его','её','их','не','ни','из','по']);

function материалИзЖурнала(path) {
  let текст = '';
  try {
    for (const строка of readFileSync(path, 'utf8').split('\n')) {
      if (!строка.trim()) continue;
      let z;
      try { z = JSON.parse(строка); } catch { continue; }
      for (const part of z.message?.parts ?? []) {
        const r = part.functionResponse?.response;
        if (r) текст += ' ' + JSON.stringify(r);
      }
    }
  } catch { /* журнала может не быть — тогда сверять не с чем */ }
  return текст.toLowerCase();
}

function значимыеСлова(фраза) {
  return (фраза.toLowerCase().match(/[а-яёa-z0-9]{4,}/g) ?? []).filter((w) => !ШУМ.has(w));
}

/**
 * Основа слова: первые пять букв. Русский склоняется, и точное сравнение
 * обманывается — «проекта» не находилось в материале, где написано «Проект»,
 * и заявление «не найден статус проекта» проходило приёмку, хотя всё это в
 * материале было. Обрезка грубая и склоняет к строгости: лучше отклонить
 * лишний раз, чем узаконить пустышку.
 */
function основа(слово) {
  return слово.length > 5 ? слово.slice(0, 5) : слово;
}

function проверить(продукт, материал) {
  const m = /НЕ\s+НАЙДЕНО:\s*(.+)/i.exec(продукт);
  if (!m) {
    return { принято: false, причина:
      'В ответе нет обязательной строки. Последней строкой напиши:\n' +
      '`НЕ НАЙДЕНО: <какой конкретно факт ты искал в материале и не нашёл>`\n' +
      'Назови сам факт, а не сообщай, что всё выяснено.' };
  }
  const заявлено = m[1].trim();

  if (ПУСТЫШКИ.some((r) => r.test(заявлено))) {
    return { принято: false, причина:
      `Заявление «${заявлено}» ничего не называет. Обязанность требует назвать ` +
      'конкретный факт, которого в материале нет. Если такого факта нет — назови ' +
      'вопрос, на который прочитанный материал не отвечает.' };
  }

  const слова = значимыеСлова(заявлено);
  if (слова.length === 0) {
    return { принято: false, причина: `Заявление «${заявлено}» слишком общо, чтобы его проверить.` };
  }

  // Сверка с материалом: заявление «этого нет» истинно, только если хотя бы
  // одно значимое слово действительно отсутствует в прочитанном.
  const отсутствуют = слова.filter((w) => !материал.includes(основа(w)));
  if (материал && отсутствуют.length === 0) {
    return { принято: false, причина:
      `Заявлено, что «${заявлено}» не найдено, но всё названное присутствует в ` +
      'прочитанном материале. Значит это найдено. Назови то, чего в материале действительно нет.' };
  }

  return { принято: true, причина: `отсутствуют в материале: ${отсутствуют.join(', ')}` };
}

let сырое = '';
process.stdin.on('data', (c) => (сырое += c));
process.stdin.on('end', () => {
  let вход = {};
  try { вход = JSON.parse(сырое); } catch { process.exit(0); }

  const продукт = вход.last_assistant_message ?? '';
  const материал = вход.agent_transcript_path ? материалИзЖурнала(вход.agent_transcript_path) : '';
  const итог = проверить(продукт, материал);

  appendFileSync(ЖУРНАЛ,
    `${new Date().toISOString()}\t${вход.agent_type ?? '?'}\t` +
    `${итог.принято ? 'ПРИНЯТО' : 'ОТКЛОНЕНО'}\t${итог.причина.slice(0, 120).replace(/\n/g, ' ')}\n`);

  if (итог.принято) process.exit(0);
  process.stdout.write(JSON.stringify({ decision: 'block', reason: `Приёмка не пройдена. ${итог.причина}` }));
  process.exit(0);
});
