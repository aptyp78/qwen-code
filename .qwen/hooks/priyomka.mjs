#!/usr/bin/env node
/**
 * Приёмка продукта: работа принимается, если позиция выполнила объявленную
 * обязанность, а не потому, что модель перестала звать инструменты.
 *
 * Правило приёмки объявляет САМА ПОЗИЦИЯ — полем `priyomka` в своём
 * определении. Позиция без объявленного правила проходит без вмешательства.
 * Иначе приёмка мешает: требовать «назови, чего не нашёл» от позиции, которая
 * переписывает функцию, бессмысленно.
 *
 * Проверки сверяются с материалом, а не с формой ответа. Проверка формы была
 * первой редакцией и пропустила пустышку «ничего не осталось невыясненным»:
 * форма соблюдена, содержания нет.
 */

import { appendFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { найтиОпределение, разобрать, материалИзЖурнала, основа } from './lib.mjs';

/**
 * Журнал рядом с хуком — вспомогательный: его читают глазами.
 * Хук копируется вместе с проектом, и таких журналов заводится по одному на
 * каждую копию. Сверка по ним невозможна.
 */
const ЖУРНАЛ_ДЛЯ_ГЛАЗ = join(dirname(fileURLToPath(import.meta.url)), 'priyomka.log');

/**
 * Канонический след кладётся рядом с паспортом позиции.
 *
 * Первая редакция писала только журнал рядом с хуком. Паспорта при этом лежат
 * в общем ~/.qwen/projects/**, и два встречных следа оказались в разных
 * системах координат: сверка брала паспорта отовсюду, а журнал — только свой,
 * и объявляла «приёмка не отработала» на всех восьми позициях, включая те, где
 * она отработала. Датчик, который врёт всегда, хуже отсутствующего: его
 * перестают читать, и настоящий отказ проходит незамеченным.
 */
function записатьСлед(вход, запись) {
  const строка = JSON.stringify(запись) + '\n';
  let легло = false;
  try {
    if (вход.agent_transcript_path) {
      appendFileSync(
        join(dirname(resolve(вход.agent_transcript_path)),
          `agent-${вход.agent_id ?? 'без-имени'}.priyomka.jsonl`),
        строка,
      );
      легло = true;
    }
  } catch { /* канонический след не лёг — остаётся журнал для глаз */ }
  try {
    appendFileSync(ЖУРНАЛ_ДЛЯ_ГЛАЗ,
      `${запись.время}\t${запись.агент}\t${запись.позиция}\t${запись.правило}\t` +
      `${запись.итог}\t${(запись.причина ?? '').slice(0, 110).replace(/\n/g, ' ')}` +
      `${легло ? '' : '\tСЛЕД-НЕ-ЛЁГ'}\n`);
  } catch { /* приёмка не должна ломать работу агента */ }
}

const ПУСТЫШКИ = [
  /ничего не оста/i, /всё выяснен/i, /все выяснен/i, /нет невыясн/i,
  /данных достаточно/i, /вопросов нет/i, /полностью прочитан/i, /^\s*(нет|—|-)\s*$/i,
];
const ШУМ = new Set(['этот','эта','было','быть','есть','весь','вся','все','для','как','что','или','при','над','под','его','её','их','него','неё','них']);

const значимые = (ф) => (ф.toLowerCase().match(/[а-яёa-z0-9]{4,}/g) ?? []).filter((w) => !ШУМ.has(w));

/** Набор правил. Позиция называет одно из них полем `priyomka`. */
const ПРАВИЛА = {
  /** Позиция обязана назвать границу материала: что искала и не нашла. */
  границаМатериала(продукт, материал) {
    const m = /НЕ\s+НАЙДЕНО:\s*(.+)/i.exec(продукт);
    if (!m) return { принято: false, причина:
      'В ответе нет обязательной строки. Последней строкой напиши:\n' +
      '`НЕ НАЙДЕНО: <какой конкретно факт ты искал в материале и не нашёл>`\n' +
      'Назови сам факт, а не сообщай, что всё выяснено.' };
    const заявлено = m[1].trim();
    if (ПУСТЫШКИ.some((r) => r.test(заявлено))) return { принято: false, причина:
      `Заявление «${заявлено}» ничего не называет. Назови конкретный факт, ` +
      'которого в материале нет, либо вопрос, на который материал не отвечает.' };
    const слова = значимые(заявлено);
    if (!слова.length) return { принято: false, причина: `Заявление «${заявлено}» слишком общо, чтобы его проверить.` };
    const низ = материал.toLowerCase();
    const отсутствуют = слова.filter((w) => !низ.includes(основа(w)));
    if (материал && !отсутствуют.length) return { принято: false, причина:
      `Заявлено, что «${заявлено}» не найдено, но всё названное присутствует в ` +
      'прочитанном материале. Назови то, чего в материале действительно нет.' };
    return { принято: true, причина: `отсутствуют в материале: ${отсутствуют.join(', ')}` };
  },

  /**
   * Позиция обязана предъявить продукт в объявленной ею форме.
   *
   * Метки называет сама позиция полем `metki` — правило не может их знать:
   * у выделителя одни, у сводчика другие, и зашитый список сделал бы правило
   * правилом одной позиции.
   *
   * Нужно потому, что форму не проверял никто, и модель в трёх прогонах подряд
   * писала «ЦИТАЯ» вместо «ЦИТАТА». Разбор продукта по меткам на этом ломается,
   * а вчера это обошли регулярным выражением в скрипте разбора — то есть
   * починили в конвейере, а не в позиции.
   */
  формаОтвета(продукт, материал, поля) {
    const метки = (поля.metki ?? '').split(',').map((м) => м.trim()).filter(Boolean);
    if (!метки.length) return { принято: true, причина: 'позиция меток не назвала' };
    const экранировать = (м) => м.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const нет = метки.filter((м) => !new RegExp(`^\\s*${экранировать(м)}\\s*:`, 'mi').test(продукт));
    if (нет.length) return { принято: false, причина:
      `В ответе нет обязательных меток: ${нет.join(', ')}. Каждая строка продукта ` +
      'начинается с метки и двоеточия, ровно как объявлено. Пиши метку буква в букву.' };
    return { принято: true, причина: `меток на месте: ${метки.length}` };
  },

  /** Позиция обязана подтвердить сказанное дословной выдержкой из материала. */
  цитатаИзМатериала(продукт, материал) {
    const цитаты = [...продукт.matchAll(/«([^»]{12,})»|"([^"]{12,})"/g)]
      .map((m) => (m[1] ?? m[2]).trim());
    if (!цитаты.length) return { принято: false, причина:
      'В ответе нет ни одной выдержки из материала. Подтверди сказанное ' +
      'дословной цитатой в «кавычках» — не менее двенадцати символов.' };
    const низ = материал.toLowerCase().replace(/\s+/g, ' ');
    const выдуманные = цитаты.filter((ц) => !низ.includes(ц.toLowerCase().replace(/\s+/g, ' ')));
    if (выдуманные.length) return { принято: false, причина:
      `Этих выдержек в материале нет дословно: ${выдуманные.map((ц) => `«${ц}»`).join(', ')}. ` +
      'Приведи то, что действительно есть в прочитанном, или сними утверждение.' };
    return { принято: true, причина: `цитат подтверждено: ${цитаты.length}` };
  },
};

// Выключатель: ASO_PRIYOMKA=off снимает приёмку, не трогая настройки.
// Нужен на случай, когда приёмка мешает срочной работе: править settings.json
// под нагрузкой — верный способ оставить его сломанным.
if ((process.env.ASO_PRIYOMKA ?? '').toLowerCase() === 'off') process.exit(0);

let сырое = '';
process.stdin.on('data', (c) => (сырое += c));
process.stdin.on('end', () => {
  let вход = {};
  try { вход = JSON.parse(сырое); } catch { process.exit(0); }

  const опр = найтиОпределение(вход.agent_type ?? '', вход.cwd ?? process.cwd());
  const поля = опр ? разобрать(опр.текст).поля : {};

  // Обязанностей у позиции может быть несколько: `priyomka: цитатаИзМатериала, формаОтвета`.
  // Первая редакция брала одно имя, и выделителю не хватало: цитата дословная
  // проверялась, а форма продукта — никем. Одиночное имя работает как раньше.
  const названные = (поля.priyomka ?? '').split(',').map((и) => и.trim()).filter(Boolean);
  const известные = названные.filter((и) => ПРАВИЛА[и]);
  const неизвестные = названные.filter((и) => !ПРАВИЛА[и]);

  // Опечатка в имени не блокирует работу, но и не исчезает: она в следе.
  if (неизвестные.length) записатьСлед(вход, {
    время: new Date().toISOString(),
    агент: вход.agent_id ?? '?',
    позиция: вход.agent_type,
    правило: неизвестные.join(', '),
    итог: 'ПРОПУЩЕНО',
    причина: `неизвестные правила: ${неизвестные.map((и) => `«${и}»`).join(', ')}`,
  });

  // Позиция не объявила ни одного известного правила — приёмка не вмешивается.
  if (!известные.length) process.exit(0);
  const имяПравила = известные.join('+');

  const материал = вход.agent_transcript_path ? материалИзЖурнала(вход.agent_transcript_path) : '';

  // Пустой материал означает не «всё сошлось», а «сверить не с чем», и это
  // должно быть громко. Первая редакция этого не различала: `границаМатериала`
  // при пустом материале объявляла все названные слова отсутствующими и
  // ПРИНИМАЛА заявление, записывая в след «отсутствуют в материале: …» — о
  // материале, которого не читала. Защита `if (материал && …)` была написана,
  // но стояла во второй половине условия и не срабатывала никогда.
  //
  // Отклонять безопасно: продукт ограничивает блокирующие обороты (по
  // умолчанию восемь, packages/core/src/hooks/stopHookCap.ts), поэтому
  // отклонение не может подвесить работу навсегда.
  if (!материал.trim()) {
    // Два разных положения дел, и позиция отвечает только за первое.
    const журналЕсть = Boolean(вход.agent_transcript_path) && existsSync(вход.agent_transcript_path);
    const причина = журналЕсть
      ? 'Ты не обращалась к материалу: в журнале работы нет ни одного ответа орудия. ' +
        'Прочитай материал и опирайся на прочитанное, а не на память.'
      : 'Журнал работы недоступен — сверить продукт не с чем. Прочитай материал ' +
        'заново инструментом чтения; если журнал не появится, работу принимать нельзя.';
    записатьСлед(вход, {
      время: new Date().toISOString(),
      агент: вход.agent_id ?? '?',
      позиция: вход.agent_type,
      правило: имяПравила,
      итог: 'НЕ-СВЕРЕНО',
      причина: журналЕсть ? 'журнал пуст: позиция не звала орудий' : 'журнал недоступен',
    });
    process.stdout.write(JSON.stringify({ decision: 'block', reason: `Приёмка не пройдена. ${причина}` }));
    process.exit(0);
  }

  // Все обязанности проверяются за один оборот, и причины уходят вместе.
  // Проверять по одной значило бы гонять позицию через оборот на каждую, а
  // оборот на локальной машине стоит секунд.
  const продукт = вход.last_assistant_message ?? '';
  const итоги = известные.map((и) => ({ имя: и, ...ПРАВИЛА[и](продукт, материал, поля) }));
  const провал = итоги.filter((и) => !и.принято);
  const итог = провал.length
    ? { принято: false, причина: провал.map((и) => `[${и.имя}] ${и.причина}`).join('\n\n') }
    : { принято: true, причина: итоги.map((и) => `${и.имя}: ${и.причина}`).join('; ') };

  // agent_id обязателен: сверка «правило объявлено, а приёмка не отработала»
  // по типу позиции даёт ложное благополучие — след от другого запуска той же
  // позиции засчитывается за этот.
  записатьСлед(вход, {
    время: new Date().toISOString(),
    агент: вход.agent_id ?? '?',
    позиция: вход.agent_type,
    правило: имяПравила,
    итог: итог.принято ? 'ПРИНЯТО' : 'ОТКЛОНЕНО',
    причина: итог.причина,
  });

  if (итог.принято) process.exit(0);
  process.stdout.write(JSON.stringify({ decision: 'block', reason: `Приёмка не пройдена. ${итог.причина}` }));
  process.exit(0);
});
