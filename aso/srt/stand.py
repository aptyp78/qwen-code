"""Стенд разнопозиционного акта.

Проверяет вторую ступень СРТ: даёт ли различие позиций содержание,
которого нет ни в одном исходном корпусе.

Позиция = тройка (знаниевые средства, машина превращения, обязанность).
Такт по своду Макина: предъявление -> вопрос к содержанию -> правка понятия.

Запуск:  python3 stand.py            разнопозиционный прогон
         python3 stand.py --control  контроль: одна модель, один корпус, амплуа
"""
import json, sys, time, urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
API = "http://127.0.0.1:11434/v1/chat/completions"
CONTROL = "--control" in sys.argv
RUN = "control" if CONTROL else "multi"
LOG = HERE / f"journal_{RUN}.jsonl"

ЗАДАЧА = (
    "Агент останавливается и не может продолжить работу. Практика различает три "
    "разных положения, но общий язык называет их одинаково — «агент упёрся». "
    "Нужно построить различение: чем РАЗРЫВ отличается от ОШИБКИ и от НЕЗНАНИЯ. "
    "Различение должно быть таким, чтобы по нему можно было решать, что делать "
    "дальше, и чтобы его можно было проверить машинно, без участия человека."
)

def корпус(имя):
    return (HERE / "corpus" / f"{имя}.md").read_text(encoding="utf-8")

ПОЗИЦИИ = [
    {
        "id": "ММК",
        "модель": "qwen3.8:27b-mlx",
        "средства": корпус("mmk"),
        "обязанность": (
            "Ты ОБЯЗАН в каждом своём тексте называть основание, по которому "
            "проведено различение, и отдельно называть то, что твоя схема "
            "оставляет неразличённым. Это требование безусловно: выполняй его "
            "даже когда ответ кажется тебе полным."
        ),
    },
    {
        "id": "Талеб",
        "модель": "gemma4:31b-mlx",
        "средства": корпус("taleb"),
        "обязанность": (
            "Ты ОБЯЗАН в каждом своём тексте называть асимметрию последствий: "
            "чем дороже ошибиться в одну сторону, чем в другую, и что происходит "
            "при бездействии. Это требование безусловно: выполняй его даже когда "
            "асимметрия кажется тебе несущественной."
        ),
    },
    {
        "id": "Практик",
        "модель": "muse-glimmer:30b-mxfp8-dflash",
        "средства": корпус("praktik"),
        "обязанность": (
            "Ты ОБЯЗАН проверять каждое различение на конкретном случае из "
            "своего журнала и отбраковывать то, что нельзя проверить машинно — "
            "то есть по файлу, коду возврата или содержимому вывода, без "
            "человеческой оценки. Это требование безусловно."
        ),
    },
]

КОНТРОЛЬ = [
    {"id": "Оптимист", "модель": "qwen3.8:27b-mlx", "амплуа": "Ты оптимист: ищешь работающее решение и веришь, что оно есть."},
    {"id": "Скептик",  "модель": "qwen3.8:27b-mlx", "амплуа": "Ты скептик: сомневаешься в предлагаемых решениях."},
    {"id": "Критик",   "модель": "qwen3.8:27b-mlx", "амплуа": "Ты критик: находишь слабые места в рассуждениях."},
]

ОБЩИЙ_КОРПУС = корпус("mmk") + "\n\n---\n\n" + корпус("taleb") + "\n\n---\n\n" + корпус("praktik")

def зов(модель, система, запрос, бюджет=3000):
    тело = json.dumps({
        "model": модель,
        "messages": [{"role": "system", "content": система},
                     {"role": "user", "content": запрос}],
        "max_tokens": бюджет, "temperature": 0.7,
    }).encode()
    req = urllib.request.Request(API, data=тело, headers={"Content-Type": "application/json"})
    t0 = time.time()
    with urllib.request.urlopen(req, timeout=1200) as r:
        d = json.loads(r.read())
    m = d["choices"][0]["message"]
    return {
        "content": (m.get("content") or "").strip(),
        "reasoning": (m.get("reasoning") or "").strip(),
        "секунд": round(time.time() - t0, 1),
        "токенов": d["usage"]["completion_tokens"],
        "финиш": d["choices"][0]["finish_reason"],
    }

def пиши(**поля):
    with LOG.open("a", encoding="utf-8") as f:
        f.write(json.dumps(поля, ensure_ascii=False) + "\n")

def система(поз):
    if CONTROL:
        return (f"{поз['амплуа']}\n\nТвои средства — материалы ниже.\n\n"
                f"=== МАТЕРИАЛЫ ===\n{ОБЩИЙ_КОРПУС}\n\n"
                "Отвечай по-русски, плотно, без вступлений и без списков-перечислений ради объёма.")
    return (f"Ты занимаешь позицию «{поз['id']}» в разнопозиционной работе.\n\n"
            f"ТВОИ СРЕДСТВА. Ты смотришь на предмет ТОЛЬКО через них. Других у тебя нет.\n\n"
            f"{поз['средства']}\n\n"
            f"ТВОЯ ОБЯЗАННОСТЬ.\n{поз['обязанность']}\n\n"
            "Отвечай по-русски, плотно, без вступлений. Не пересказывай свои средства — "
            "работай ими по предмету задачи.")

if __name__ == "__main__":
    состав = КОНТРОЛЬ if CONTROL else ПОЗИЦИИ
    LOG.write_text("", encoding="utf-8")
    пиши(событие="старт", прогон=RUN, задача=ЗАДАЧА,
         состав=[{k: v for k, v in p.items() if k in ("id", "модель")} for p in состав])

    # ── раунд 1: предъявление ────────────────────────────────────────────────
    тексты = {}
    for p in состав:
        print(f"[1/предъявление] {p['id']} на {p['модель']} …", flush=True)
        r = зов(p["модель"], система(p),
                f"ЗАДАЧА.\n{ЗАДАЧА}\n\nПредъяви своё различение. Одним связным текстом.")
        тексты[p["id"]] = r["content"]
        пиши(событие="предъявление", позиция=p["id"], модель=p["модель"], **r)
        print(f"    {r['секунд']}с, {r['токенов']} токенов, {len(r['content'])} символов", flush=True)

    # ── раунд 2: вопросы к содержанию ────────────────────────────────────────
    вопросы = {p["id"]: {} for p in состав}
    for p in состав:
        чужие = "\n\n".join(f"=== ТЕКСТ ПОЗИЦИИ «{i}» ===\n{t}" for i, t in тексты.items() if i != p["id"])
        print(f"[2/вопросы] {p['id']} …", flush=True)
        r = зов(p["модель"], система(p),
                f"ЗАДАЧА.\n{ЗАДАЧА}\n\n{чужие}\n\n"
                "Задай КАЖДОМУ из этих текстов ровно один вопрос К СОДЕРЖАНИЮ его различения. "
                "Вопрос к содержанию спрашивает про предмет: что именно различается, на каком "
                "основании, что остаётся неразличённым. Это НЕ оценка текста и НЕ совет его "
                "улучшить. Формат строго такой, без иного текста:\n"
                "К «имя позиции»: <вопрос>")
        for строка in r["content"].splitlines():
            if строка.strip().startswith("К «") and ":" in строка:
                кому = строка.split("«", 1)[1].split("»", 1)[0].strip()
                вопросы.setdefault(кому, {})[p["id"]] = строка.split(":", 1)[1].strip()
        пиши(событие="вопросы", позиция=p["id"], разобрано=len(r["content"].splitlines()), **r)
        print(f"    {r['секунд']}с", flush=True)

    # ── раунд 3: правка понятия или удержание ────────────────────────────────
    for p in состав:
        мои = вопросы.get(p["id"], {})
        if not мои:
            пиши(событие="правка", позиция=p["id"], пропуск="вопросов не поступило")
            print(f"[3/правка] {p['id']} — вопросов нет", flush=True)
            continue
        свод = "\n".join(f"Вопрос от «{к}»: {в}" for к, в in мои.items())
        print(f"[3/правка] {p['id']} — {len(мои)} вопрос(ов) …", flush=True)
        r = зов(p["модель"], система(p),
                f"ЗАДАЧА.\n{ЗАДАЧА}\n\nТВОЙ ПРЕЖНИЙ ТЕКСТ:\n{тексты[p['id']]}\n\n"
                f"ВОПРОСЫ К ТВОЕМУ СОДЕРЖАНИЮ:\n{свод}\n\n"
                "Ответь на вопросы. Если вопрос вскрыл, что твоё различение неполно или "
                "неверно — перестрой его и предъяви заново. Если различение выдерживает "
                "вопрос — удержи его и скажи, почему вопрос не задевает основания. "
                "Прямо укажи в конце одной строкой: ПЕРЕСТРОЕНО или УДЕРЖАНО.")
        пиши(событие="правка", позиция=p["id"], вопросов=len(мои), **r)
        print(f"    {r['секунд']}с — {'ПЕРЕСТРОЕНО' if 'ПЕРЕСТРОЕНО' in r['content'] else 'УДЕРЖАНО' if 'УДЕРЖАНО' in r['content'] else '?'}", flush=True)

    пиши(событие="конец", прогон=RUN)
    print(f"\nЖурнал: {LOG}", flush=True)
