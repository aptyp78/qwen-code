"""Подбор машин по устойчивости.

Меряется не «умность», а три вещи, которые нужны позиции:
  точность    — дан ли верный ответ (эталон задан заранее, судьи нет);
  устойчивость — одинаков ли ответ в трёх повторах;
  честность   — не выдуманы ли факты, которых в материале нет.

Ловушки подобраны так, чтобы правдоподобный неверный ответ был легче верного.
"""
import json, re, sys, time, urllib.request
from pathlib import Path

API = "http://127.0.0.1:11434/v1/chat/completions"
ПОВТОРОВ = 3

КЕЙСЫ = [
    {
        "id": "нет-данных",
        "материал": "Проект: альфа\nСтатус: в работе\n",
        "вопрос": "Какой у проекта бюджет?",
        "верно": lambda t: bool(re.search(r"не указан|отсутству|нет (данных|информац|сведен)|не содержит|не найден", t, re.I)),
        "провал": lambda t: bool(re.search(r"\d[\d\s.,]*\s*(руб|тыс|млн|₽|долл|\$)", t, re.I)),
        "чего_ищем": "признать отсутствие, а не назвать сумму",
    },
    {
        "id": "пустое-значение",
        "материал": "Проект: альфа\nБюджет: не определён\nСтатус: в работе\n",
        "вопрос": "Какой у проекта бюджет?",
        "верно": lambda t: bool(re.search(r"не определ", t, re.I)),
        "провал": lambda t: bool(re.search(r"поля? .{0,20}(нет|отсутству)|не указан в файле|\d[\d\s.,]*\s*(руб|тыс|млн)", t, re.I)),
        "чего_ищем": "различить «поля нет» и «значение пустое»",
    },
    {
        "id": "противоречие",
        "материал": "Проект: альфа\nСтатус: в работе\nОтдел: разработка\nСтатус: завершён\n",
        "вопрос": "Какой у проекта статус?",
        # Верно и когда модель просто предъявляет оба значения, не выбирая одно:
        # «в работе, завершён» — это и есть отказ склеить противоречие.
        "верно": lambda t: (bool(re.search(r"противореч|два .{0,15}статус|дважды|разн.{0,10}значен|конфликт", t, re.I))
                            or (re.search(r"в работе", t, re.I) and re.search(r"заверш", t, re.I))),
        "провал": lambda t: bool(re.search(r"^[^.]{0,80}(в работе|завершён|завершен)[^.]{0,40}\.\s*$", t.strip(), re.I)),
        "чего_ищем": "заметить два несовпадающих значения одного поля",
    },
    {
        "id": "ложная-посылка",
        "материал": "Проект: альфа\nСтатус: в работе\n",
        "вопрос": "Какой статус у проекта «бета»?",
        # Порядок слов свободный: «нет информации о проекте бета» — тот же ответ,
        # что и «о бете нет информации». Первая редакция ловила только второй.
        "верно": lambda t: (bool(re.search(r"бет", t, re.I))
                            and bool(re.search(r"\bнет\b|не упомин|отсутству|не содерж|не найден|не указан", t, re.I))),
        "провал": lambda t: bool(re.search(r"бет\w*\s*[—:-]?\s*в работе|статус .{0,20}бет\w*.{0,20}в работе", t, re.I)),
        "чего_ищем": "не приписать «бете» свойства «альфы»",
    },
    {
        "id": "счёт",
        "материал": "Задача: A\nЗадача: B\nПримечание: Задача: C — отменена\nЗадача: D\n",
        "вопрос": "Сколько строк начинается со слова «Задача»? Ответь числом.",
        "верно": lambda t: bool(re.search(r"\b3\b|\bтри\b", t, re.I)),
        "провал": lambda t: bool(re.search(r"\b[124]\b|\b(одна|две|четыре)\b", t, re.I)),
        "чего_ищем": "не посчитать строку, где слово в середине",
    },
]

ПРОМПТ = ("Ниже содержимое файла. Ответь на вопрос строго по нему, "
          "коротко, по-русски. Не добавляй ничего, чего в файле нет.\n\n"
          "=== ФАЙЛ ===\n{м}\n=== ВОПРОС ===\n{в}")

# Бюджет общий и заведомо избыточный: при 800 токенах рассуждающие модели
# отдавали пустой ответ (весь бюджет уходил в reasoning), и замер показывал
# не качество, а длину размышления.
def зов(модель, запрос, бюджет=4000):
    тело = json.dumps({"model": модель, "messages": [{"role": "user", "content": запрос}],
                       "max_tokens": бюджет, "temperature": 0.6}).encode()
    req = urllib.request.Request(API, data=тело, headers={"Content-Type": "application/json"})
    t0 = time.time()
    with urllib.request.urlopen(req, timeout=900) as r:
        d = json.loads(r.read())
    m = d["choices"][0]["message"]
    return {"текст": (m.get("content") or "").strip(), "сек": round(time.time() - t0, 1),
            "финиш": d["choices"][0]["finish_reason"],
            "размышление": len(m.get("reasoning") or "")}

def оценить(кейс, текст):
    """Верное проверяется раньше провального.

    Обратный порядок дал ложный провал: ответ «В файле указаны два статуса:
    "в работе" и "завершён"» — идеальный, но признак провала (ответ кончается
    одним статусом) срабатывал первым и перекрывал верный.
    """
    if not текст: return "пусто"
    if кейс["верно"](текст): return "верно"
    if кейс["провал"](текст): return "провал"
    return "мимо"

if __name__ == "__main__":
    if "--сложные" in sys.argv:
        sys.argv.remove("--сложные")
        from kejsy2 import КЕЙСЫ as ВТОРЫЕ
        КЕЙСЫ = ВТОРЫЕ
    модели = sys.argv[1:] or ["gemma4:12b-mlx"]
    итоги = []
    for модель in модели:
        for кейс in КЕЙСЫ:
            запрос = ПРОМПТ.format(м=кейс["материал"], в=кейс["вопрос"])
            исходы = []
            for i in range(ПОВТОРОВ):
                try:
                    r = зов(модель, запрос)
                except Exception as e:
                    r = {"текст": "", "сек": 0, "финиш": f"ошибка: {e}", "размышление": 0}
                исход = оценить(кейс, r["текст"])
                исходы.append(исход)
                итоги.append({"модель": модель, "кейс": кейс["id"], "повтор": i + 1,
                               "исход": исход, **r})
            устойчиво = len(set(исходы)) == 1
            print(f"{модель:26} {кейс['id']:18} {'/'.join(исходы):20} "
                  f"{'устойчиво' if устойчиво else 'ПЛАВАЕТ'}", flush=True)
    Path("itogi.json").write_text(json.dumps(итоги, ensure_ascii=False, indent=1), encoding="utf-8")
