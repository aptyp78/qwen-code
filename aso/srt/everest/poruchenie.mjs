#!/usr/bin/env node
/**
 * Поручение на множество материала со сборкой продукта.
 *
 * Средство организатора, а не конвейер. Разница проходит по одной черте:
 * конвейер зовёт модель своим промптом и сам разбирает ответ — тогда модель
 * есть орудие в его руках, без позиции, без обязанности и без приёмки. Это
 * средство раздаёт поручения ПОЗИЦИЯМ и собирает их продукт; материала оно не
 * касается вовсе.
 *
 * Два устройства, без которых сборка врёт:
 *
 *   1. Продукт берётся из журнала субагента, а не из ответа родителя. Родитель
 *      не пересказывает — он сочиняет: в живом прогоне доложил о понятиях,
 *      которых в определении позиции нет, и о «фиксации результата в системе»,
 *      которой не было. Разрыв Р2.
 *
 *   2. Годным считается продукт, который приняла приёмка, а не тот, в котором
 *      есть текст. След приёмки лежит рядом с журналом.
 *
 * Прогон переживает обрыв: уже собранное не переделывается. 53 отрывка на
 * локальной машине идут больше часа, и потеря середины стоит дороже проверки.
 *
 * Запуск из корня репозитория:
 *   node aso/srt/everest/poruchenie.mjs --skolko 3
 *   node aso/srt/everest/poruchenie.mjs --vse --model gemma4:12b-mlx
 */
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { homedir } from 'node:os';
import { execFileSync } from 'node:child_process';
import { разобрать } from '../../../.qwen/hooks/lib.mjs';

const дов = (имя, поум) => {
  const i = process.argv.indexOf(`--${имя}`);
  return i > -1 && process.argv[i + 1] && !process.argv[i + 1].startsWith('--') ? process.argv[i + 1] : поум;
};

const СТЕНД = join(homedir(), 'materialy', 'everest', 'stend');
const ПОЗИЦИЯ = дов('pozitsiya', 'vydelitel');
const МОДЕЛЬ = дов('model', 'gemma4:12b-mlx');
const СКОЛЬКО = process.argv.includes('--vse') ? Infinity : Number(дов('skolko', 3));
const СВОД = join(СТЕНД, 'svod', `${ПОЗИЦИЯ}.json`);

// Каталог следов: qwen кодирует путь проекта, заменяя разделители на дефисы.
const СЛЕДЫ = join(homedir(), '.qwen', 'projects', `-${СТЕНД.slice(1).replaceAll('/', '-')}`, 'subagents');

/** Метки берутся из определения позиции — там же, откуда их берёт приёмка. */
function меткиПозиции() {
  const путь = join(СТЕНД, '.qwen', 'agents', `${ПОЗИЦИЯ}.md`);
  const { поля } = разобрать(readFileSync(путь, 'utf8'));
  return (поля.metki ?? '').split(',').map((м) => м.trim()).filter(Boolean);
}

/** Все файлы следов, какие есть сейчас: по ним ищутся новые после запуска. */
function снимокСледов() {
  const было = new Set();
  if (!existsSync(СЛЕДЫ)) return было;
  for (const сессия of readdirSync(СЛЕДЫ)) {
    for (const ф of readdirSync(join(СЛЕДЫ, сессия))) было.add(join(сессия, ф));
  }
  return было;
}

/** Продукт позиции и вердикт приёмки по следам, появившимся после запуска. */
function продуктИзСледов(было, метки) {
  let журнал = null;
  for (const сессия of existsSync(СЛЕДЫ) ? readdirSync(СЛЕДЫ) : []) {
    for (const ф of readdirSync(join(СЛЕДЫ, сессия))) {
      const ключ = join(сессия, ф);
      if (было.has(ключ)) continue;
      // След приёмки тоже кончается на .jsonl и по алфавиту идёт последним:
      // без этого условия он затирал журнал, сборка искала след рядом с самим
      // следом и честно докладывала «следа нет». Поймано первым же прогоном
      // на живом материале.
      if (ф.startsWith(`agent-${ПОЗИЦИЯ}-`) && ф.endsWith('.jsonl') && !ф.endsWith('.priyomka.jsonl')) {
        журнал = join(СЛЕДЫ, ключ);
      }
    }
  }
  if (!журнал) return { годен: false, почему: 'журнал субагента не появился' };

  // Продукт — последнее предъявление, содержащее объявленные метки.
  let продукт = null;
  for (const строка of readFileSync(журнал, 'utf8').split('\n')) {
    if (!строка.trim()) continue;
    let z; try { z = JSON.parse(строка); } catch { continue; }
    for (const ч of z.message?.parts ?? []) {
      const т = ч.text ?? '';
      if (метки.length && метки.every((м) => new RegExp(`^\\s*${м}\\s*:`, 'mi').test(т))) продукт = т.trim();
    }
  }

  // Вердикт приёмки: годно то, что она приняла, а не то, в чём есть текст.
  const следПриёмки = журнал.replace(/\.jsonl$/, '.priyomka.jsonl');
  let вердикт = null, оборотов = 0;
  if (existsSync(следПриёмки)) {
    const записи = readFileSync(следПриёмки, 'utf8').split('\n').filter((с) => с.trim())
      .map((с) => { try { return JSON.parse(с); } catch { return null; } }).filter(Boolean);
    оборотов = записи.length;
    вердикт = записи.at(-1)?.итог ?? null;
  }
  if (вердикт !== 'ПРИНЯТО') return { годен: false, почему: `приёмка: ${вердикт ?? 'следа нет'}`, оборотов, продукт };
  if (!продукт) return { годен: false, почему: 'приёмка приняла, но меток в продукте нет', оборотов };
  return { годен: true, продукт, оборотов };
}

/** Разбор продукта по меткам: сборка требует разбираемого, а не связного. */
function поМеткам(текст, метки) {
  const из = {};
  for (const м of метки) {
    const r = new RegExp(`^\\s*${м}\\s*:\\s*(.+?)\\s*$`, 'mi').exec(текст);
    if (r) из[м] = r[1];
  }
  return из;
}

const метки = меткиПозиции();
const отрывки = readdirSync(join(СТЕНД, 'otryvki')).filter((ф) => ф.endsWith('.txt')).sort();
mkdirSync(join(СТЕНД, 'svod'), { recursive: true });
const собрано = existsSync(СВОД) ? JSON.parse(readFileSync(СВОД, 'utf8')) : {};

console.log(`позиция ${ПОЗИЦИЯ} · машина ${МОДЕЛЬ} · отрывков ${отрывки.length} · уже собрано ${Object.keys(собрано).length}`);

let сделано = 0;
for (const отрывок of отрывки) {
  if (собрано[отрывок]?.годен) continue;          // прогон переживает обрыв
  if (сделано >= СКОЛЬКО) break;
  сделано++;

  const было = снимокСледов();
  const поручение = `Поручи позиции ${ПОЗИЦИЯ} разобрать отрывок otryvki/${отрывок}. ` +
    `Сам отрывок не читай и разметку не делай — только передай позиции задание.`;
  try {
    execFileSync(join(homedir(), 'bin', 'qwen'), ['-y', '-m', МОДЕЛЬ, '-p', поручение],
      { cwd: СТЕНД, stdio: 'ignore', timeout: 15 * 60 * 1000 });
  } catch (е) {
    // Обрыв одного поручения не должен уносить остальные.
    собрано[отрывок] = { годен: false, почему: `запуск не удался: ${е.code ?? е.message}` };
    console.log(`✗ ${отрывок}  запуск не удался`);
    writeFileSync(СВОД, JSON.stringify(собрано, null, 2) + '\n');
    continue;
  }

  const итог = продуктИзСледов(было, метки);
  собрано[отрывок] = итог.годен
    ? { годен: true, оборотов: итог.оборотов, поля: поМеткам(итог.продукт, метки), продукт: итог.продукт }
    : { годен: false, почему: итог.почему, оборотов: итог.оборотов ?? 0 };
  writeFileSync(СВОД, JSON.stringify(собрано, null, 2) + '\n');   // пишем сразу, а не в конце

  console.log(итог.годен
    ? `✓ ${отрывок}  оборотов ${итог.оборотов}  ${собрано[отрывок].поля[метки[1]] ?? ''}  ${(собрано[отрывок].поля[метки[0]] ?? '').slice(0, 44)}`
    : `✗ ${отрывок}  ${итог.почему}`);
}

const годных = Object.values(собрано).filter((з) => з.годен).length;
console.log(`\nсобрано годных: ${годных} из ${отрывки.length} · свод: ${СВОД}`);
