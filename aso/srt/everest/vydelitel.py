"""Позиция «выделитель кейсов»: находит в материале нарушение технологии
и называет отказавший компонент акта деятельности.

Обязанность: подтверждать дословной цитатой. Цитата проверяется машинно —
судья не участвует, придуманная цитата отбраковывается до всякой оценки.
"""
import json, re, time, urllib.request
from pathlib import Path

API = "http://127.0.0.1:11434/api/chat"  # нативный: позволяет снять размышление
МОДЕЛЬ = "gemma4:12b-mlx"

ЗАДАНИЕ = """Ты разбираешь документальный текст о восхождении на Эверест 1996 года.

Найди в отрывке случай НАРУШЕНИЯ технологии безопасного восхождения — то есть
место, где принятый порядок действий не был соблюдён, или где условие
безопасности оказалось не выполнено.

Назови, какой компонент деятельности отказал. Выбери ровно один:
- ОРУДИЕ — не хватило или отказало снаряжение: кислород, верёвки, рации
- МАШИНА — не сработало то, что должно было снять с человека операцию: перила, лестницы, кислородная система
- ЦЕЛЬ — цель подменилась: вместо возвращения живым стала вершина любой ценой
- ЗНАНИЕ — не было нужных сведений: прогноз, состояние людей, положение на маршруте
- ТАБЛО — отказало само восприятие: гипоксия, спутанность, неспособность оценить положение
- ОПЕРАЦИЯ — нарушен порядок или сроки: не повернули вовремя, пошли не в том порядке

Ответь строго в таком виде, без вступлений:

КЕЙС: <короткое имя случая, до семи слов>
КОМПОНЕНТ: <одно слово из списка выше>
ЧТО: <что именно произошло, одно предложение>
ЦИТАТА: «<дословный кусок из отрывка, 10-30 слов, подтверждающий сказанное>»

Если нарушения в отрывке нет — ответь одним словом: НЕТ."""

# Бюджет заведомо избыточный и проверка на пустой ответ обязательны.
# Рассуждающая модель съедает бюджет размышлением и возвращает пустое поле;
# внешне это неотличимо от «нечего сказать». Наступал на это трижды за день.
def зов(запрос, бюджет=5000):
    тело = json.dumps({"model": МОДЕЛЬ, "think": False, "stream": False,
                       "messages": [{"role": "user", "content": запрос}],
                       "options": {"num_predict": бюджет, "temperature": 0.3}}).encode()
    req = urllib.request.Request(API, data=тело, headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=900) as r:
        d = json.loads(r.read())
    текст = (d.get("message", {}).get("content") or "").strip()
    if not текст:
        raise RuntimeError('пустой ответ модели — подними бюджет')
    return текст

def норм(s):
    return re.sub(r"\s+", " ", s.lower().replace("ё", "е")).strip()

фрагменты = json.loads(Path("fragmenty.json").read_text(encoding="utf-8"))
кейсы, отбраковано, пусто = [], 0, 0

for i, ф in enumerate(фрагменты, 1):
    try:
        ответ = зов(f"{ЗАДАНИЕ}\n\n=== ОТРЫВОК ===\n{ф}")
    except Exception as e:
        print(f"{i:3}/{len(фрагменты)} ошибка: {e}", flush=True); continue
    if ответ.strip().upper().startswith("НЕТ"):
        пусто += 1; print(f"{i:3}/{len(фрагменты)} нет кейса", flush=True); continue

    Path("syrye.jsonl").open("a", encoding="utf-8").write(
        json.dumps({"фрагмент": i, "ответ": ответ}, ensure_ascii=False) + "\n")
    # Метки ищутся терпимо: модель написала «ЦИТАЯ» вместо «ЦИТАТА», и требование
    # точного слова отбраковало бы верный кейс из-за опечатки в разметке.
    МЕТКИ = {"КЕЙС": r"КЕЙС", "КОМПОНЕНТ": r"КОМПОНЕНТ", "ЧТО": r"ЧТО", "ЦИТАТА": r"ЦИТА\w*"}
    п = {k: (re.search(rf"{м}:\s*(.+)", ответ) or [None, ""])[1].strip()
         for k, м in МЕТКИ.items()}
    if not п["ЦИТАТА"]:
        m = re.search(r"«([^»]{20,})»", ответ)
        п["ЦИТАТА"] = m.group(1) if m else ""
    цитата = п["ЦИТАТА"].strip("«»\"' ")
    if not цитата or норм(цитата) not in норм(ф):
        отбраковано += 1
        print(f"{i:3}/{len(фрагменты)} ✗ цитата не найдена в отрывке: «{цитата[:60]}»", flush=True)
        continue
    п["ЦИТАТА"] = цитата
    п["фрагмент"] = i
    кейсы.append(п)
    print(f"{i:3}/{len(фрагменты)} ✓ {п['КОМПОНЕНТ']:10} {п['КЕЙС'][:52]}", flush=True)

Path("kejsy.json").write_text(json.dumps(кейсы, ensure_ascii=False, indent=1), encoding="utf-8")
print(f"\nкейсов принято: {len(кейсы)} · отбраковано по цитате: {отбраковано} · без кейса: {пусто}")
